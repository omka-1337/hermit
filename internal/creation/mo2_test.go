func TestParseNexusFile(t *testing.T) {
	for _, tc := range []struct {
		name    string
		id      int
		version string
		ok      bool
	}{
		{"SkyUI-12604-6-11-1778020881.zip", 12604, "6.11", true},
		{"Lux (main)-43158-7-0-1753427726.rar", 43158, "7.0", true},
		{"FNIS Behavior SE 7_6-3038-7-6-1582048023.7z", 3038, "7.6", true},
		{"LSAR_SE_for_build2.0.20_ver1.5.97-15326-SE2-0-20-ver1-5-97-1665414822.7z", 15326, "SE2.0.20.ver1.5.97", true},
		{"Address Library All in One (1.7.104.0) v13 32444 13 2026-08-27T15-29Z Ae46W7Fw2.zip", 32444, "13", true},
		{"Unofficial Skyrim Special Edition Patch 266 4.3.9c 2026-09-05T22-22Z lNkz9LChN.7z", 266, "4.3.9c", true},
		{"OStim Standalone 7.0.7z", 0, "", false},
	} {
		id, version, ok := ParseNexusFile(tc.name)
		if id != tc.id || version != tc.version || ok != tc.ok {
			t.Errorf("%s: got %d %q %v, want %d %q %v", tc.name, id, version, ok, tc.id, tc.version, tc.ok)
		}
	}
}

func TestReadAndImportMO2(t *testing.T) {
	mo2 := t.TempDir()
	write(t, mo2, map[string]string{
		"ModOrganizer.ini": "[General]\ngameName=Skyrim Special Edition\n" +
			`gamePath=@ByteArray(Z:\\games\\Skyrim Special Edition)` + "\nselected_profile=@ByteArray(Main)\n",
		"profiles/Main/modlist.txt": "# This file was automatically generated by Mod Organizer.\r\n" +
			"+Patch\r\n-Old\r\n-UI_separator\r\n+SkyUI\r\n*DLC: Dawnguard\r\n",
		"profiles/Main/loadorder.txt":    "Skyrim.esm\r\nSkyUI_SE.esp\r\nPatch.esp\r\nOld.esp\r\n",
		"profiles/Main/plugins.txt":      "*SkyUI_SE.esp\r\n*Patch.esp\r\nOld.esp\r\n",
		"profiles/Other/":                "",
		"mods/SkyUI/SkyUI_SE.esp":        "ui",
		"mods/SkyUI/meta.ini":            "[General]\nmodid=12604\nversion=d2026.10.26\ninstallationFile=Z:/home/u/Downloads/SkyUI-12604-6-11-1778020881.zip\n",
		"mods/Patch/Patch.esp":           "patch",
		"mods/Patch/meta.ini":            "[General]\nmodid=0\nversion=1.0\ncomments=\"Generated, load last\"\n",
		"mods/Old/Old.esp":               "old",
		"mods/UI_separator/meta.ini":     "[General]\nmodid=0\n",
		"overwrite/SKSE/log.txt":         "log",
		"profiles/Main/settings.ini":     "[General]\nLocalSettings=true\n",
		"profiles/Main/skyrimprefs.ini":  "[Display]\nfGamma=0.96\n",
		"profiles/Main/skyrimcustom.ini": "",
	})
	in, err := ReadMO2(mo2)
	if err != nil {
		t.Fatal(err)
	}
	if in.GameName != "Skyrim Special Edition" || in.GamePath != "/games/Skyrim Special Edition" || in.Selected != "Main" ||
		!slices.Equal(in.Profiles, []string{"Main", "Other"}) {
		t.Fatalf("instance: %+v", in)
	}
	p, err := in.ReadProfile("Main")
	if err != nil {
		t.Fatal(err)
	}
	want := []MO2Mod{
		{Folder: "SkyUI", Enabled: true, NexusID: 12604, Version: "6.11", File: "SkyUI-12604-6-11-1778020881.zip"},
		{Folder: "UI_separator", Separator: true},
		{Folder: "Old", Enabled: false},
		{Folder: "Patch", Enabled: true, Version: "1.0", Comments: "Generated, load last"},
	}
	if !slices.Equal(p.Mods, want) {
		t.Fatalf("mods:\n got  %+v\n want %+v", p.Mods, want)
	}
	if want := []Plugin{{"Skyrim.esm", false}, {"SkyUI_SE.esp", true}, {"Patch.esp", true}, {"Old.esp", false}}; !slices.Equal(p.Plugins, want) {
		t.Fatalf("plugins: %v", p.Plugins)
	}

	gameData := t.TempDir()
	write(t, gameData, map[string]string{"Skyrim.esm": "master"})
	profile := t.TempDir()
	g, _ := Find("SkyrimSE.exe")
	if err := in.ImportMO2(p, []string{"skyui", "ui-separator", "old", "patch"}, profile, gameData, g.INIs); err != nil {
		t.Fatal(err)
	}
	if got := read(t, filepath.Join(profile, "mods", "skyui", "SkyUI_SE.esp")); got != "ui" {
		t.Errorf("imported file: %q", got)
	}
	if _, err := os.Stat(filepath.Join(profile, "mods", "ui-separator")); !os.IsNotExist(err) {
		t.Error("a separator got a mod folder")
	}
	if p.Mods[1].SeparatorName() != "UI" {
		t.Errorf("separator heading %q", p.Mods[1].SeparatorName())
	}
	if got := read(t, filepath.Join(profile, "overwrite", "SKSE", "log.txt")); got != "log" {
		t.Errorf("overwrite: %q", got)
	}
	// Linked, not copied: MO2 keeps its files and they cost no space.
	a, _ := os.Stat(filepath.Join(mo2, "mods", "Patch", "Patch.esp"))
	b, _ := os.Stat(filepath.Join(profile, "mods", "patch", "Patch.esp"))
	if !os.SameFile(a, b) {
		t.Error("files were copied within one file system")
	}
	if got := read(t, filepath.Join(profile, "ini", "SkyrimPrefs.ini")); got != "[Display]\nfGamma=0.96\n" {
		t.Errorf("profile's prefs: %q", got)
	}
	if _, err := os.Stat(filepath.Join(profile, "ini", "SkyrimCustom.ini")); !os.IsNotExist(err) {
		t.Error("an empty ini was imported")
	}
	plugins, _ := ReadPlugins(filepath.Join(profile, "plugins.txt"))
	if want := []Plugin{{"SkyUI_SE.esp", true}, {"Patch.esp", true}, {"Old.esp", false}}; !slices.Equal(plugins, want) {
		t.Errorf("profile plugins: %v", plugins)
	}
}
